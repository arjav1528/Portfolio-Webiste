async (page) => {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  await page.goto('http://127.0.0.1:3001');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  const tilt = page.locator('.tilt-stage');
  await tilt.hover({ position: { x: 70, y: 80 } });
  await page.waitForFunction(() => document.querySelector('.tilted-surface').style.transform.includes('rotate'));
  const magnet = page.locator('.hero-actions .magnet-target');
  await magnet.hover({ position: { x: 25, y: 20 } });
  await page.waitForFunction(() => document.querySelector('.hero-actions .magnet-surface').style.transform.includes('translate'));
  await page.locator('.decrypted-text').hover();
  await page.waitForFunction(() => [...document.querySelectorAll('.decrypt-glyph')].map(e => e.textContent).join('') !== 'CODE.');
  await page.waitForFunction(() => [...document.querySelectorAll('.decrypt-glyph')].map(e => e.textContent).join('') === 'CODE.');
  check(await page.locator('.decrypted-text .sr-only').textContent() === 'CODE.', 'Accessible text stays intact');
  const card = page.locator('.project-card').first();
  await card.hover({ position: { x: 80, y: 80 } });
  check(await card.evaluate(el => el.style.getPropertyValue('--spotlight-active')) === '1', 'Project spotlight follows pointer');
  await page.getByRole('button', { name: 'Web', exact: true }).click();
  check(await page.locator('.button-ripple').count() === 1, 'Click creates a ripple');
  await page.waitForFunction(() => !document.querySelector('.button-ripple'));
  const filter = page.getByRole('button', { name: 'Mobile', exact: true });
  await filter.focus();
  await page.keyboard.press('Enter');
  check(await page.locator('.project-card').count() === 1, 'Keyboard still activates filters');
  const rippleLeft = await page.locator('.button-ripple').evaluate(el => parseFloat(el.style.left));
  const filterWidth = await filter.evaluate(el => el.getBoundingClientRect().width);
  check(Math.abs(rippleLeft + filterWidth / 2) < 2, 'Keyboard ripple starts from button center');
  await page.getByRole('button', { name: /^All work/ }).click();
  await page.getByRole('button', { name: 'Pause motion' }).click();
  await tilt.hover({ position: { x: 80, y: 70 } });
  check(await page.locator('.tilted-surface').evaluate(el => getComputedStyle(el).transform) === 'none', 'Paused tilt resets');
  await card.hover({ position: { x: 90, y: 90 } });
  check(await card.evaluate(el => getComputedStyle(el, '::after').opacity) === '0', 'Paused spotlight is hidden');
  await page.getByRole('button', { name: 'Web', exact: true }).click();
  check(await page.locator('.button-ripple').count() === 0, 'Paused click has no animated ripple');
  await page.getByRole('button', { name: 'Play motion' }).click();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await tilt.hover({ position: { x: 80, y: 70 } });
  check(await page.locator('.tilted-surface').evaluate(el => getComputedStyle(el).transform) === 'none', 'OS reduced motion disables tilt');
  await page.getByRole('button', { name: 'AI & data', exact: true }).click();
  check(await page.locator('.button-ripple').count() === 0, 'OS reduced motion disables ripples');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.getByRole('button', { name: /^All work/ }).click();
  await page.mouse.move(0, 0);
  await card.dispatchEvent('pointermove', { pointerType: 'touch', clientX: 120, clientY: 120 });
  check(await card.evaluate(el => el.style.getPropertyValue('--spotlight-active')) !== '1', 'Touch does not enable a hover effect');
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async value => { window.__copiedEmail = value; } } }));
  await page.getByRole('button', { name: 'Copy email address' }).click();
  await page.getByRole('status').filter({ hasText: 'Email address copied.' }).waitFor();
  check(await page.evaluate(() => window.__copiedEmail) === 'arjav1528@gmail.com', 'Correct email copied');
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('Clipboard denied'); } } }));
  await page.getByRole('button', { name: 'Copy email address' }).click();
  await page.getByRole('status').filter({ hasText: 'Couldn’t copy.' }).waitFor();
  check(await page.locator('.scroll-progress').evaluate(el => getComputedStyle(el).transform !== 'none'), 'Scroll progress responds to position');
  await page.goto('http://127.0.0.1:3001');
  return { passed: true, checks: ['portrait tilt', 'magnetic CTA', 'decryption settles', 'card spotlight', 'click and keyboard ripples', 'motion pause', 'reduced motion', 'touch fallback', 'clipboard success and failure', 'scroll progress'] };
}
